function translateTextNode(node: Text): void {
  const parent = node.parentElement;
  if (!parent || parent.closest(uiTranslationSkipSelector)) return;
  const raw = node.nodeValue || "";
  const trimmed = raw.trim();
  if (!trimmed) return;
  const translated = legacyEnglish[trimmed] ?? translatePatternText(trimmed);
  if (!translated || translated === trimmed) return;
  node.nodeValue = raw.replace(trimmed, translated);
}

function translateAttributes(root: ParentNode): void {
  const elements = root instanceof Element
    ? [root, ...Array.from(root.querySelectorAll<HTMLElement>("[title],[aria-label],[placeholder]"))]
    : Array.from(root.querySelectorAll<HTMLElement>("[title],[aria-label],[placeholder]"));
  for (const element of elements) {
    if (element.closest(uiAttributeSkipSelector)) continue;
    for (const attribute of ["title", "aria-label", "placeholder"]) {
      const value = element.getAttribute(attribute);
      if (!value) continue;
      const translated = legacyEnglish[value.trim()] ?? translatePatternText(value.trim());
      if (translated && translated !== value.trim()) {
        element.setAttribute(attribute, value.replace(value.trim(), translated));
      }
    }
  }
}

function translateTree(root: ParentNode): void {
  if (locale !== "en-US") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  for (const node of nodes) translateTextNode(node);
  if (root instanceof Element || root instanceof DocumentFragment) translateAttributes(root);
}

export function translateUI(root: ParentNode = document): void {
  if (locale !== "en-US") return;
  translateTree(root);
}

let uiTranslationObserver: MutationObserver | null = null;

export function startUITranslationObserver(): void {
  if (typeof document === "undefined" || uiTranslationObserver) return;
  uiTranslationObserver = new MutationObserver(records => {
    if (locale !== "en-US") return;
    for (const record of records) {
      if (record.type === "characterData") {
        if (record.target instanceof Text) translateTextNode(record.target);
        continue;
      }
      if (record.type === "attributes") {
        if (record.target instanceof Element) translateAttributes(record.target);
        continue;
      }
      for (const node of Array.from(record.addedNodes)) {
        if (node instanceof Text) {
          translateTextNode(node);
        } else if (node instanceof Element || node instanceof DocumentFragment) {
          translateTree(node);
        }
      }
    }
  });
  uiTranslationObserver.observe(document.body, {subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["title", "aria-label", "placeholder"]});
}
