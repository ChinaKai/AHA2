let locale: Locale = "zh-CN";

export function normalizeLanguagePreference(value: unknown): LanguagePreference {
  const text = String(value || "").trim();
  if (text === "zh-CN" || text === "en-US") return text;
  return "auto";
}

export function resolveLocale(preference: unknown): Locale {
  const normalized = normalizeLanguagePreference(preference);
  if (normalized !== "auto") return normalized;
  const browser = (typeof navigator !== "undefined" ? navigator.language : "zh-CN") || "zh-CN";
  return browser.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

export function applyLocale(preference: unknown): Locale {
  locale = resolveLocale(preference);
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale;
    document.documentElement.dataset.locale = locale;
    // The saved language arrives after the first paint. Translate whatever is
    // already on screen (for example the boot "Connecting to service…" card)
    // instead of waiting for the next render to replace it.
    if (locale === "en-US" && document.body) translateUI(document.body);
  }
  return locale;
}

export function currentLocale(): Locale {
  return locale;
}

export function t(key: string, values: Record<string, string | number> = {}): string {
  const catalog = locale === "en-US" ? enUS : zhCN;
  const template = catalog[key] ?? zhCN[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function formatLocaleNumber(value: number): string {
  return new Intl.NumberFormat(locale).format(value);
}

export function formatLocaleDateTime(value: string | number | Date, options?: Intl.DateTimeFormatOptions): string {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return locale === "en-US" ? "Unknown" : "未知";
  return date.toLocaleString(locale, options);
}

export function tr(text: string): string {
  if (locale !== "en-US") return text;
  return legacyEnglish[text] ?? legacyEnglish[text.trim()] ?? text;
}

